/**
 * Regenerates src/lib/devices/windows-releases.ts from Microsoft's own release
 * health pages.
 *
 *   pnpm windows:refresh
 *
 * The dashboard needs to say how far behind Microsoft a machine is — "ตามหลัง
 * 15 แพตช์ · 184 วัน" — and that can only be answered against Microsoft's
 * published revision history, which the Starcat database does not carry.
 *
 * That history is transcribed rather than fetched at runtime on purpose: this
 * dashboard runs on an office LAN and must not depend on reaching the internet
 * to render a page. The cost of that choice is that the table goes stale, so it
 * is generated by a script you can re-run on Patch Tuesday instead of being
 * hand-edited, and it stamps the date it was built so a stale table shows up in
 * the UI rather than quietly reporting last month's numbers.
 *
 * Source of truth:
 *   https://learn.microsoft.com/windows/release-health/windows11-release-information
 *   https://learn.microsoft.com/windows/release-health/release-information
 */
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = resolve(projectRoot, "src/lib/devices/windows-releases.ts");

const SOURCES = [
  {
    product: "Windows 11",
    url: "https://learn.microsoft.com/en-us/windows/release-health/windows11-release-information",
  },
  {
    product: "Windows 10",
    url: "https://learn.microsoft.com/en-us/windows/release-health/release-information",
  },
];

/**
 * Only the builds this fleet actually runs are kept. The full set is thousands
 * of rows across a decade of Windows; carrying builds nobody owns would bloat
 * the bundle to no purpose. Add a build here when the fleet gains one — the
 * dashboard reports an unknown build plainly rather than guessing.
 */
const KEEP_BUILDS = new Set(["19045", "22621", "22631", "26100", "26120", "26200"]);

async function fetchText(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${url} → HTTP ${response.status}`);
  }
  return response.text();
}

/** Every table row on the page, as its list of plain-text cells. */
function parseRows(html) {
  return [...html.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/gi)].map((row) =>
    [...row[1].matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/gi)].map((cell) =>
      cell[1]
        .replace(/<[^>]+>/g, " ")
        .replace(/&nbsp;/g, " ")
        .replace(/&amp;/g, "&")
        .replace(/\s+/g, " ")
        .trim(),
    ),
  );
}

/**
 * Pulls every revision row out of the per-version history tables. The pages put
 * the same columns in a different order from table to table, so rows are
 * matched on shape — an ISO date cell, a `build.ubr` cell — rather than on
 * column position, which is also what stops a layout change from silently
 * producing a plausible-looking wrong table.
 */
function parseRevisions(rows) {
  const byBuild = new Map();

  for (const cells of rows) {
    const buildIndex = cells.findIndex((cell) => /^\d{5}\.\d+$/.test(cell));
    if (buildIndex < 0) continue;
    const buildCell = cells[buildIndex];

    // The date wanted is the one nearest the build on its left. In the history
    // tables that is the revision's own release date; in the summary table at
    // the top of the page it is "Latest revision date" — whereas the *first*
    // date in either row is the feature version's availability date, which is
    // years off.
    const dateCell = cells
      .slice(0, buildIndex)
      .filter((cell) => /^\d{4}-\d{2}-\d{2}$/.test(cell))
      .pop();
    if (!dateCell) continue;

    const [build, ubr] = buildCell.split(".");
    if (!KEEP_BUILDS.has(build)) continue;

    const kbCell = cells.find((cell) => /KB\d{7}/.test(cell));
    const kb = kbCell ? /KB\d{7}/.exec(kbCell)[0] : null;

    const revisions = byBuild.get(build) ?? new Map();
    // The pages list a revision once per table it appears in; first wins, and
    // they agree.
    if (!revisions.has(ubr)) {
      revisions.set(ubr, { ubr: Number(ubr), date: dateCell, kb });
    }
    byBuild.set(build, revisions);
  }

  return byBuild;
}

/**
 * The servicing summary table at the top of each page: when a feature version
 * shipped and when its updates stop. "End of updates" is spelled out as text
 * rather than a date once a version is past it.
 */
function parseServicing(rows) {
  const byVersion = new Map();

  for (const cells of rows) {
    if (!/^\d{2}H\d$/.test(cells[0]?.replace(/\^.*$/, "").trim() ?? "")) continue;

    const version = cells[0].replace(/\^.*$/, "").trim();
    const availabilityIndex = cells.findIndex((cell) =>
      /^\d{4}-\d{2}-\d{2}$/.test(cell),
    );
    const buildIndex = cells.findIndex((cell) => /^\d{5}\.\d+$/.test(cell));
    if (availabilityIndex < 0 || buildIndex < 0) continue;

    const build = cells[buildIndex].split(".")[0];
    if (!KEEP_BUILDS.has(build)) continue;

    // Row shape, both on the GA table and the LTSC one:
    //   version | servicing | availability | end… | end… | latest update |
    //   latest revision date | latest build
    // The end-of-updates columns are everything between availability and the
    // trailing "latest …" trio. Slicing to the build cell instead would pick up
    // the latest revision date and report a version as expiring this month.
    const endCells = cells.slice(availabilityIndex + 1, buildIndex - 2);

    // The fleet is entirely Professional, so the first end column — Home, Pro,
    // Pro Education, Pro for Workstations — is the one that applies. Enterprise
    // is typically a year later and would overstate how long these have.
    const endOfUpdates = endCells[0] ?? null;

    byVersion.set(build, {
      version,
      availability: cells[availabilityIndex],
      endOfServicing: /^\d{4}-\d{2}-\d{2}$/.test(endOfUpdates ?? "")
        ? endOfUpdates
        : null,
      ended: /End of updates/i.test(endOfUpdates ?? ""),
    });
  }

  return byVersion;
}

const builds = new Map();

for (const source of SOURCES) {
  const rows = parseRows(await fetchText(source.url));
  const revisionsByBuild = parseRevisions(rows);
  const servicingByBuild = parseServicing(rows);

  for (const [build, revisions] of revisionsByBuild) {
    const sorted = [...revisions.values()].sort((a, b) => b.ubr - a.ubr);
    const servicing = servicingByBuild.get(build);

    builds.set(build, {
      build: Number(build),
      product: source.product,
      featureVersion: servicing?.version ?? null,
      availability: servicing?.availability ?? null,
      endOfServicing: servicing?.ended ? null : (servicing?.endOfServicing ?? null),
      // Past its last update: what the dashboard flags as unsupported.
      ended: servicing?.ended ?? false,
      revisions: sorted,
    });
  }
}

if (builds.size === 0) {
  throw new Error("parsed no builds — Microsoft changed the page layout");
}

const generatedAt = new Date().toISOString().slice(0, 10);

const body = [...builds.values()]
  .sort((a, b) => b.build - a.build)
  .map((entry) => {
    const revisions = entry.revisions
      .map((r) => `    { ubr: ${r.ubr}, date: "${r.date}", kb: ${r.kb ? `"${r.kb}"` : "null"} },`)
      .join("\n");
    return `  "${entry.build}": {
    product: "${entry.product}",
    featureVersion: ${entry.featureVersion ? `"${entry.featureVersion}"` : "null"},
    availability: ${entry.availability ? `"${entry.availability}"` : "null"},
    endOfServicing: ${entry.endOfServicing ? `"${entry.endOfServicing}"` : "null"},
    ended: ${entry.ended},
    revisions: [
${revisions}
    ],
  },`;
  })
  .join("\n");

const file = `// GENERATED FILE — do not edit by hand.
// Regenerate with \`pnpm windows:refresh\` (scripts/build-windows-releases.mjs).
//
// Microsoft's published servicing history for the Windows builds this fleet
// runs, transcribed so the dashboard can say how far behind a machine is
// without reaching the internet at render time. Re-run this after each Patch
// Tuesday; the UI surfaces \`GENERATED_ON\` so a stale table is visible.

export type WindowsRevision = {
  /** The part after the dot in 26200.9168. */
  ubr: number;
  /** ISO date Microsoft released it. */
  date: string;
  kb: string | null;
};

export type WindowsBuild = {
  product: string;
  /** "25H2" — the feature version this build is. */
  featureVersion: string | null;
  availability: string | null;
  /** ISO date updates stop, or null when they already have. */
  endOfServicing: string | null;
  /** True once Microsoft lists it as past its last update. */
  ended: boolean;
  /** Newest first. */
  revisions: WindowsRevision[];
};

/** The date this table was built from Microsoft's pages. */
export const GENERATED_ON = "${generatedAt}";

export const WINDOWS_BUILDS: Record<string, WindowsBuild> = {
${body}
};
`;

writeFileSync(OUTPUT, file, "utf8");

console.log(`wrote ${OUTPUT}`);
for (const entry of builds.values()) {
  console.log(
    `  ${entry.build} (${entry.featureVersion ?? "?"}) — ${entry.revisions.length} revisions, latest .${entry.revisions[0].ubr} on ${entry.revisions[0].date}`,
  );
}
